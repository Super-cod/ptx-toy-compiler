#include "PTXEmitter.hpp"
#include <sstream>
#include <unordered_set>

namespace ptxcc {

std::string PTXEmitter::format_operand(const Operand& op) {
    if (op.is_imm()) {
        return std::to_string(op.imm_val);
    }
    return op.name;
}

std::string PTXEmitter::emit(const IRProgram& program) {
    std::ostringstream oss;
    oss << "// Generated by ptxcc (NVIDIA PTX Toy Compiler)\n";
    oss << ".version 7.0\n";
    oss << ".target sm_75\n";
    oss << ".address_size 64\n\n";

    for (const auto& k : program.kernels) {
        oss << emit_kernel(k) << "\n";
    }
    return oss.str();
}

std::string PTXEmitter::emit_kernel(const IRKernel& kernel) {
    std::ostringstream oss;

    oss << ".visible .entry " << kernel.name << "(\n";
    for (size_t i = 0; i < kernel.params.size(); ++i) {
        oss << "    .param .u32 " << kernel.params[i];
        if (i + 1 < kernel.params.size()) {
            oss << ",\n";
        }
    }
    oss << "\n)\n{\n";

    // Collect all registers and predicates used
    std::unordered_set<std::string> regs;
    std::unordered_set<std::string> preds;

    for (const auto& inst : kernel.instructions) {
        if (inst.dst.is_reg()) regs.insert(inst.dst.name);
        if (inst.dst.is_pred()) preds.insert(inst.dst.name);
        if (inst.src1.is_reg()) regs.insert(inst.src1.name);
        if (inst.src1.is_pred()) preds.insert(inst.src1.name);
        if (inst.src2.is_reg()) regs.insert(inst.src2.name);
        if (inst.src2.is_pred()) preds.insert(inst.src2.name);
    }

    if (!regs.empty()) {
        oss << "    .reg .s32 %r<" << (regs.size() + 10) << ">;\n";
    }
    if (!preds.empty()) {
        oss << "    .reg .pred %p<" << (preds.size() + 5) << ">;\n";
    }
    oss << "\n";

    // Load parameters into registers
    size_t param_idx = 0;
    for (const auto& inst : kernel.instructions) {
        if (inst.opcode == IROpCode::PARAM) {
            oss << "    ld.param.s32 " << inst.dst.name << ", [" << kernel.params[param_idx++] << "];\n";
        }
    }
    if (param_idx > 0) oss << "\n";

    // Emit instructions
    for (const auto& inst : kernel.instructions) {
        if (inst.opcode == IROpCode::PARAM) {
            // Handled above
            continue;
        }

        switch (inst.opcode) {
            case IROpCode::LABEL:
                oss << inst.dst.name << ":\n";
                break;
            case IROpCode::MOV:
                oss << "    mov.s32 " << inst.dst.name << ", " << format_operand(inst.src1) << ";\n";
                break;
            case IROpCode::ADD:
                oss << "    add.s32 " << inst.dst.name << ", " << format_operand(inst.src1) << ", " << format_operand(inst.src2) << ";\n";
                break;
            case IROpCode::SUB:
                oss << "    sub.s32 " << inst.dst.name << ", " << format_operand(inst.src1) << ", " << format_operand(inst.src2) << ";\n";
                break;
            case IROpCode::MUL:
                oss << "    mul.lo.s32 " << inst.dst.name << ", " << format_operand(inst.src1) << ", " << format_operand(inst.src2) << ";\n";
                break;
            case IROpCode::DIV:
                oss << "    div.s32 " << inst.dst.name << ", " << format_operand(inst.src1) << ", " << format_operand(inst.src2) << ";\n";
                break;
            case IROpCode::MOD:
                oss << "    rem.s32 " << inst.dst.name << ", " << format_operand(inst.src1) << ", " << format_operand(inst.src2) << ";\n";
                break;
            case IROpCode::NEG:
                oss << "    neg.s32 " << inst.dst.name << ", " << format_operand(inst.src1) << ";\n";
                break;
            case IROpCode::SETP_EQ:
                oss << "    setp.eq.s32 " << inst.dst.name << ", " << format_operand(inst.src1) << ", " << format_operand(inst.src2) << ";\n";
                break;
            case IROpCode::SETP_NEQ:
                oss << "    setp.ne.s32 " << inst.dst.name << ", " << format_operand(inst.src1) << ", " << format_operand(inst.src2) << ";\n";
                break;
            case IROpCode::SETP_LT:
                oss << "    setp.lt.s32 " << inst.dst.name << ", " << format_operand(inst.src1) << ", " << format_operand(inst.src2) << ";\n";
                break;
            case IROpCode::SETP_LTE:
                oss << "    setp.le.s32 " << inst.dst.name << ", " << format_operand(inst.src1) << ", " << format_operand(inst.src2) << ";\n";
                break;
            case IROpCode::SETP_GT:
                oss << "    setp.gt.s32 " << inst.dst.name << ", " << format_operand(inst.src1) << ", " << format_operand(inst.src2) << ";\n";
                break;
            case IROpCode::SETP_GTE:
                oss << "    setp.ge.s32 " << inst.dst.name << ", " << format_operand(inst.src1) << ", " << format_operand(inst.src2) << ";\n";
                break;
            case IROpCode::BRA:
                oss << "    bra " << inst.dst.name << ";\n";
                break;
            case IROpCode::BRA_COND:
                oss << "    @" << inst.src1.name << " bra " << inst.dst.name << ";\n";
                break;
            case IROpCode::BRA_COND_NOT:
                oss << "    @!" << inst.src1.name << " bra " << inst.dst.name << ";\n";
                break;
            case IROpCode::RET:
                oss << "    ret;\n";
                break;
            case IROpCode::PARAM:
                break;
        }
    }

    oss << "}\n";
    return oss.str();
}

} // namespace ptxcc
